-- ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ
--
-- 1. Таблицы товаров. Каталог сейчас живёт в коде (src/data.js), поэтому
--    цену в заказ кладёт браузер. Это нормально для витрины, но перед
--    приёмом настоящих денег backend обязан пересчитывать сумму сам —
--    иначе её можно подменить через консоль браузера. Варианта два:
--    держать прайс в backend или завести таблицу products и считать по ней.
--
-- 2. Политик RLS для anon. Это не забывчивость: по ТЗ пишет только backend
--    под service_role. Если открыть запись из браузера, любой сможет
--    создать заказ с произвольной суммой и статусом PAID.
--
-- 3. Логики вебхуков. SQL хранит данные, но не ходит в CDEK и не слушает
--    платёжную систему. Это код backend: POST /api/payment/webhook,
--    POST /api/cdek/create, POST /api/cdek/webhook.
